#!/usr/bin/env python3
"""Generate link stubs for a test executable that links the translated image.

Tests such as runtime/tests/guest_native_test.cpp call translated guest
functions directly without the host runtime. The image still references every
kernel/XAM import and every mid-asm hook, so the linker needs a definition for
each. These stubs only exist to link: reaching one aborts the test with its
name. Hooks the test itself defines are passed on the command line.

  python tools/gen_guest_test_stubs.py <ppc dir> <output.cpp> [hook names to skip...]
"""

from __future__ import annotations

import re
import sys
from pathlib import Path

IMPORT_RE = re.compile(r"PPC_EXTERN_FUNC\(__imp__(\w+)\);")
HOOK_RE = re.compile(r"^extern (void|bool) (Mojo\w+)\(([^)]*)\);$", re.MULTILINE)


def main(argv: list[str]) -> int:
    if len(argv) < 3:
        print(__doc__.strip())
        return 2
    ppc = Path(argv[1])
    out = Path(argv[2])
    skip = set(argv[3:])

    shared = ppc / "ppc_recomp_shared.h"
    if not shared.is_file():
        raise SystemExit(f"missing {shared}; run XenonRecomp first")
    imports = list(dict.fromkeys(IMPORT_RE.findall(shared.read_text(encoding="utf-8"))))

    hooks: dict[tuple[str, str], str] = {}
    for path in sorted(ppc.glob("ppc_recomp.*.cpp")):
        for result, name, params in HOOK_RE.findall(path.read_text(encoding="utf-8")):
            if name not in skip:
                hooks[(name, params)] = result

    body = [
        "// Generated by tools/gen_guest_test_stubs.py. Do not edit by hand.",
        "// Link-only definitions for tests that call translated guest code.",
        "",
        '#include "ppc_recomp_shared.h"',
        "",
        "#include <cstdio>",
        "#include <cstdlib>",
        "",
        "namespace {",
        "[[noreturn]] void GuestTestStubReached(const char* name)",
        "{",
        '    std::fprintf(stderr, "FAIL: guest test reached the link stub %s\\n", name);',
        "    std::abort();",
        "}",
        "} // namespace",
        "",
        'extern "C" void MojoRecompTraceIndirectCall(uint32_t, uint32_t, uint32_t) {}',
        'extern "C" void MojoRecompMmioStoreU32(uint8_t*, uint32_t, uint32_t)',
        "{",
        '    GuestTestStubReached("MojoRecompMmioStoreU32");',
        "}",
        "",
    ]
    for name in imports:
        body += [f'PPC_FUNC(__imp__{name}) {{ GuestTestStubReached("{name}"); }}']
    body.append("")
    for (name, params), result in sorted(hooks.items()):
        body += [f'{result} {name}({params}) {{ GuestTestStubReached("{name}"); }}']
    body.append("")

    output = "\n".join(body)
    current = out.read_text(encoding="utf-8") if out.is_file() else None
    if current != output:
        out.parent.mkdir(parents=True, exist_ok=True)
        out.write_text(output, encoding="utf-8", newline="\n")
    print(f"guest test stubs: {len(imports)} imports, {len(hooks)} hooks -> {out}")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
